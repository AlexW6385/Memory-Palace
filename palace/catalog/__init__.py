"""The fixed vocabularies shared by content, layout, LLM prompts and the 3D viewer.

props.json  – 3D props (built by web/js/props/*), poses, hats, animations, arrangements
rooms.json  – room styles (floors, supports, walls, roofs, decor)

Both files are generated by build_props.py / build_rooms.py in this folder.
"""
from __future__ import annotations

import json
from pathlib import Path

_DIR = Path(__file__).resolve().parent

_props = json.loads((_DIR / "props.json").read_text(encoding="utf-8"))
_rooms = json.loads((_DIR / "rooms.json").read_text(encoding="utf-8"))

PROPS: dict[str, dict] = {p["name"]: p for p in _props["props"]}
POSES: list[str] = _props["poses"]
HATS: list[str] = _props["hats"]
ANIMS: list[str] = _props["anims"]
ARRANGES: list[str] = _props["arranges"]
BACKDROP_PATTERNS: list[str] = _props["backdrop_patterns"]

ROOM_STYLES: dict[str, dict] = _rooms["styles"]
FLOORS: list[str] = _rooms["floors"]
SUPPORTS: list[str] = _rooms["supports"]
WALLS: list[str] = _rooms["walls"]
ROOFS: list[str] = _rooms["roofs"]

HOLDABLE = sorted(n for n, p in PROPS.items() if p["holdable"])
TEXT_PROPS = sorted(n for n, p in PROPS.items() if p["text"])


def prop_size(name: str) -> tuple[float, float, float]:
    w, h, d = PROPS[name]["size"]
    return w, h, d


def catalog_for_prompt() -> str:
    """Compact prop list for LLM prompts: name [w×h×d] — description (variants)."""
    lines = []
    for p in PROPS.values():
        w, h, d = p["size"]
        extra = []
        if p["variants"]:
            extra.append("variants: " + "/".join(p["variants"]))
        if p["text"]:
            extra.append("text")
        if p["holdable"]:
            extra.append("holdable")
        tail = f" ({'; '.join(extra)})" if extra else ""
        lines.append(f"- {p['name']} [{w}×{h}×{d}] {p['desc']}{tail}")
    lines += [
        "",
        f"figure/statue poses: {', '.join(POSES)}",
        f"figure hats: {', '.join(HATS)}; a figure can hold any holdable prop (hold)",
        "anim: spin (turns in place), bob (floats up and down), sway (rocks), pulse (swells a little), "
        "orbit (circles the stage centre at its distance from it), hop, swing (pendulum), flicker (like a flame)",
        f"arrange (with count): {', '.join(ARRANGES)}; backdrop patterns: {', '.join(BACKDROP_PATTERNS)}",
    ]
    return "\n".join(lines)


def rooms_for_prompt() -> str:
    return "\n".join(f"- {k}: {v['en']} — {v['desc']}" for k, v in ROOM_STYLES.items())
